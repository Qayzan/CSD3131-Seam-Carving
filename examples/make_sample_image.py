"""Draw the synthetic test picture ``assets/images/synthetic_scene.png``.

The picture is generated by this script (no photo, no third-party content), so the team can
redistribute it freely (CC0). It has what a seam-carving demo needs: large flat areas (sky,
grass) that seams should remove first, and objects with strong edges (house, tree, sun,
mountains) that should survive. Deterministic: running it twice gives the same file.

Run from the repository root:  python examples/make_sample_image.py
"""

from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np

from seam_carving.image_utils import save_image

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_PATH = ROOT / "assets" / "images" / "synthetic_scene.png"


def make_scene(height: int = 300, width: int = 480) -> np.ndarray:
    """Return the scene as an RGB uint8 array of shape (height, width, 3)."""
    image = np.zeros((height, width, 3), np.uint8)
    horizon = int(height * 0.68)

    # Sky: a smooth vertical gradient (low energy everywhere).
    t = np.linspace(0.0, 1.0, horizon)[:, None]
    top, bottom = np.array([70, 130, 210]), np.array([175, 215, 245])
    image[:horizon] = (top + (bottom - top) * t).astype(np.uint8)[:, None, :]
    # Grass: flat colour with a slight gradient.
    image[horizon:] = (80, 150, 60)

    # cv2 drawing works on BGR-or-RGB alike as long as we give colours in the array's order.
    cv2.circle(image, (int(width * 0.82), int(height * 0.17)), 26, (250, 220, 70), -1, cv2.LINE_AA)
    mountains = np.array(
        [[0, horizon], [70, 120], [140, horizon], [110, horizon], [190, 95], [270, horizon]],
        np.int32,
    )
    cv2.fillPoly(image, [mountains], (110, 110, 130), cv2.LINE_AA)
    cv2.fillPoly(image, [np.array([[70, 120], [55, 145], [85, 145]], np.int32)], (240, 240, 245))
    cv2.fillPoly(image, [np.array([[190, 95], [172, 122], [207, 122]], np.int32)], (240, 240, 245))

    # House: walls, roof, door and a window.
    x0, y0 = int(width * 0.60), horizon - 70
    cv2.rectangle(image, (x0, y0), (x0 + 90, horizon + 5), (205, 160, 110), -1)
    cv2.fillPoly(
        image,
        [np.array([[x0 - 10, y0], [x0 + 45, y0 - 40], [x0 + 100, y0]], np.int32)],
        (160, 40, 40),
    )
    cv2.rectangle(image, (x0 + 15, horizon - 35), (x0 + 35, horizon + 5), (90, 60, 40), -1)
    cv2.rectangle(image, (x0 + 52, y0 + 15), (x0 + 75, y0 + 35), (230, 240, 250), -1)
    cv2.rectangle(image, (x0 + 52, y0 + 15), (x0 + 75, y0 + 35), (60, 60, 60), 2)

    # Tree: trunk and crown.
    tx = int(width * 0.38)
    cv2.rectangle(image, (tx - 6, horizon - 45), (tx + 6, horizon + 10), (100, 70, 40), -1)
    cv2.circle(image, (tx, horizon - 60), 30, (40, 110, 45), -1, cv2.LINE_AA)
    return image


def main() -> None:
    path = save_image(DEFAULT_PATH, make_scene())
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
